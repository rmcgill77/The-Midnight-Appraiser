// Turns the built web game into the folder Capacitor packs into the app (www/).
//
//   node scripts/prepare-www.mjs [source]
//
// source: a folder holding the built site (the output of the game's `node scripts/build-site.mjs`).
// Default: ./site if it exists (the play package ships one), otherwise ../dist (the game's repo).
//
// What changes for the app, because everything ships inside it and runs offline:
//   - the service worker, its headers and the web manifest are dropped (the app itself is the install);
//   - the two Google Fonts links are replaced by fonts bundled into the app (from the @fontsource
//     packages in node_modules), so the type looks right with no network;
//   - app-version.json is written from the game's version, for the Android versionName/versionCode.

import { readFileSync, writeFileSync, mkdirSync, rmSync, cpSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = join(dirname(fileURLToPath(import.meta.url)), '..');
const arg = process.argv[2];
const SRC = arg ? join(process.cwd(), arg) : existsSync(join(HERE, 'site')) ? join(HERE, 'site') : join(HERE, '..', 'dist');
const OUT = join(HERE, 'www');

if (!existsSync(join(SRC, 'index.html'))) {
  console.error(`No built game in ${SRC}.\nBuild it first (node scripts/build-site.mjs in the game's folder) or pass the folder: node scripts/prepare-www.mjs <folder>`);
  process.exit(1);
}

rmSync(OUT, { recursive: true, force: true });
cpSync(SRC, OUT, { recursive: true });
for (const f of ['sw.js', '_headers', 'manifest.webmanifest']) rmSync(join(OUT, f), { force: true });

// Fonts the game asks for: [package, file stem, weight, style].
const FONTS = [
  ['barlow-condensed', 'Barlow Condensed', 500, 'normal'],
  ['barlow-condensed', 'Barlow Condensed', 600, 'normal'],
  ['atkinson-hyperlegible', 'Atkinson Hyperlegible', 400, 'normal'],
  ['atkinson-hyperlegible', 'Atkinson Hyperlegible', 700, 'normal'],
  ['atkinson-hyperlegible', 'Atkinson Hyperlegible', 400, 'italic'],
];
mkdirSync(join(OUT, 'fonts'), { recursive: true });
let css = '/* Bundled fonts: generated by scripts/prepare-www.mjs */\n', found = 0;
for (const [pkg, family, weight, style] of FONTS) {
  const dir = join(HERE, 'node_modules', '@fontsource', pkg, 'files');
  const have = existsSync(dir) ? readdirSync(dir) : [];
  const want = have.find(f => f === `${pkg}-latin-${weight}-${style}.woff2`) ?? have.find(f => new RegExp(`-latin-${weight}-${style}\\.woff2$`).test(f)) ?? `${pkg}-latin-${weight}-${style}.woff2`;
  if (!have.includes(want)) { console.warn(`  font missing: ${want} (the game will use its fallback font for that weight)`); continue; }
  cpSync(join(dir, want), join(OUT, 'fonts', want));
  css += `@font-face { font-family: '${family}'; font-style: ${style}; font-weight: ${weight}; font-display: swap; src: url('${want}') format('woff2'); }\n`;
  found++;
}
writeFileSync(join(OUT, 'fonts', 'fonts.css'), css);

let html = readFileSync(join(OUT, 'index.html'), 'utf8');
html = html
  .replace(/<link[^>]+rel="manifest"[^>]*>\s*/g, '')
  .replace(/<link[^>]+fonts\.(?:googleapis|gstatic)\.com[^>]*>\s*/g, '');
html = html.replace('</title>', '</title>\n<link rel="stylesheet" href="fonts/fonts.css">');
writeFileSync(join(OUT, 'index.html'), html);
if (/fonts\.(googleapis|gstatic)/.test(html)) console.warn('  warning: a Google Fonts link is still in index.html');

const config = readFileSync(join(OUT, 'src', 'config.js'), 'utf8');
const versionName = config.match(/version:\s*'([^']+)'/)?.[1] ?? '1.0.0';
const [maj = 0, min = 0, pat = 0] = versionName.split('.').map(n => parseInt(n, 10) || 0);
const versionCode = maj * 10000 + min * 100 + pat;   // 2.5.1 -> 20501; always goes up with the game
writeFileSync(join(HERE, 'app-version.json'), JSON.stringify({ versionName, versionCode }, null, 2) + '\n');

console.log(`www/ ready from ${SRC} · game ${versionName} (versionCode ${versionCode}) · ${found}/${FONTS.length} fonts bundled`);
